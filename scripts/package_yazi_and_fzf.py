        bin_dir = stage_dir / "opt" / "pacman" / "bin"
        bin_dir.mkdir(parents=True)
        man1_dir = stage_dir / "opt" / "pacman" / "share" / "man" / "man1"
        man1_dir.mkdir(parents=True)
        fzf_share = stage_dir / "opt" / "pacman" / "share" / "fzf"
        fzf_share.mkdir(parents=True)
        bash_comp = stage_dir / "opt" / "pacman" / "share" / "bash-completion" / "completions"
        bash_comp.mkdir(parents=True)
        fish_comp = stage_dir / "opt" / "pacman" / "share" / "fish" / "vendor_completions.d"
        fish_comp.mkdir(parents=True)
        zsh_comp = stage_dir / "opt" / "pacman" / "share" / "zsh" / "site-functions"
        zsh_comp.mkdir(parents=True)
        lic_dir = stage_dir / "opt" / "pacman" / "share" / "licenses" / "fzf"
        lic_dir.mkdir(parents=True)

        # Install fzf binary
        fzf_bin = stage_dir / "bin_extract" / "fzf"
        dst_fzf = bin_dir / "fzf"
        shutil.copyfile(fzf_bin, dst_fzf)
        dst_fzf.chmod(0o755)

        # Install helper scripts
        shutil.copyfile(inner_src / "bin" / "fzf-tmux", bin_dir / "fzf-tmux")
        (bin_dir / "fzf-tmux").chmod(0o755)
        shutil.copyfile(inner_src / "bin" / "fzf-preview.sh", bin_dir / "fzf-preview.sh")
        (bin_dir / "fzf-preview.sh").chmod(0o755)

        # Install man pages
        shutil.copyfile(inner_src / "man" / "man1" / "fzf.1", man1_dir / "fzf.1")
        shutil.copyfile(inner_src / "man" / "man1" / "fzf-tmux.1", man1_dir / "fzf-tmux.1")

        # Install shell completion & key-bindings
        for sh_file in (inner_src / "shell").glob("*"):
            if sh_file.is_file():
                shutil.copyfile(sh_file, fzf_share / sh_file.name)

        if (inner_src / "shell" / "completion.bash").exists():
            shutil.copyfile(inner_src / "shell" / "completion.bash", bash_comp / "fzf")
        if (inner_src / "shell" / "key-bindings.fish").exists():
            shutil.copyfile(inner_src / "shell" / "key-bindings.fish", fish_comp / "fzf.fish")
