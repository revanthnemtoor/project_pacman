    rel = "1"
    pkgver = f"{ver}-{rel}"
    print(f"\n{'='*50}\nPackaging Fzf {pkgver}...\n{'='*50}")

    bin_urls = {
        "darwin_x86_64": f"https://github.com/junegunn/fzf/releases/download/v{ver}/fzf-{ver}-darwin_amd64.tar.gz",
        "darwin_arm64": f"https://github.com/junegunn/fzf/releases/download/v{ver}/fzf-{ver}-darwin_arm64.tar.gz",
    }
    src_url = f"https://github.com/junegunn/fzf/archive/refs/tags/v{ver}.tar.gz"

    tmp_base = Path("/tmp/build_fzf")
    if tmp_base.exists():
        shutil.rmtree(tmp_base)
    tmp_base.mkdir(parents=True)

    # Download source for man pages & shell bindings
    print(f"-> Downloading fzf source for man pages and bindings...")
    req = urllib.request.Request(src_url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req) as resp:
        src_tar = resp.read()
    with tarfile.open(fileobj=io.BytesIO(src_tar), mode="r:gz") as t:
        t.extractall(tmp_base / "source")
    inner_src = tmp_base / "source" / f"fzf-{ver}"

    # Remove old packages
    for old_pkg in EXTRA_DIR.glob("fzf-0.74*"):
        print(f"  -> Removing old package: {old_pkg.name}")
        old_pkg.unlink()

    for arch, url in bin_urls.items():
        print(f"-> Processing {arch} from {url}...")
        stage_dir = tmp_base / arch
        stage_dir.mkdir(parents=True)

        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req) as resp:
            bin_tar = resp.read()
        with tarfile.open(fileobj=io.BytesIO(bin_tar), mode="r:gz") as t:
            t.extractall(stage_dir / "bin_extract")

